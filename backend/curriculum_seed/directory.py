def apply_directory(nodes,edges,node,edge):
    lookup={n["id"]:n for n in nodes}
    for bid,pages in PAGES.items():
        source=lookup["source:"+bid]
        source["data"].update(reading_status="directory_read",read_units=len(DIRECTORY_PDF_PAGES[bid]),
            total_units=None,scope="已核对完整印刷目录与页码；正文未逐页审核",
            evidence_file=lookup[bid]["title"]+".pdf",directory_pdf_pages=DIRECTORY_PDF_PAGES[bid],
            gap="正文逐课与教辅逐题仍待教师审核；不将目录读取计作原书全部已读。")
        for code,page in pages.items():
            sid=bid+":"+code
            lookup[sid]["data"].update(printed_page=page,pdf_page=page+OFFSETS[bid],directory_status="verified")
            for lesson in nodes:
                if lesson["kind"]=="lesson" and lesson["section_id"]==sid:
                    lesson["data"].update(printed_page=page,pdf_page=page+OFFSETS[bid])
    for bid,rows in CHAPTER_ENDS.items():
        for chapter,summary,review in rows:
            available=[n for n in nodes if n["kind"]=="lesson" and n["section_id"]==f"{bid}:ch:{chapter}"]
            for title,page,lesson in (("小结",summary,available[-2]),("复习参考题"+chapter,review,available[-1])):
                id=f"outline:{bid}:{chapter}:{page}"
                node(id,"outline",title,book=bid,section=f"{bid}:ch:{chapter}",printed_page=page,
                     pdf_page=page+OFFSETS[bid],source_id="source:"+bid,directory_status="verified",
                     treatment="在章末"+lesson["title"]+"中完成，题号仍待逐题核对")
                edge(id,lesson["id"],"covers","印刷目录的章末整理与习题安排到对应复习课。","source:"+bid)
                lesson["data"].update(printed_page=page,pdf_page=page+OFFSETS[bid],locator=title+"，印刷第"+str(page)+"页")
    for line in ANCILLARY.strip().splitlines():
        bid,code,page,title,body=line.split("|");page=int(page);sid=bid+":"+code
        id=f"outline:{bid}:p{page}"
        candidates=[n for n in nodes if n["kind"]=="lesson" and n["section_id"]==sid]
        lesson=max(candidates,key=lambda n:n["position"])
        # Activities printed after a chapter are integrated into chapter review,
        # while retaining their independent directory locator and learning goal.
        if title.startswith(("数学探究","数学建模")):
            candidates=[n for n in nodes if n["kind"]=="lesson" and n["section_id"]==f'{bid}:ch:{code.split(".")[0]}']
            if candidates:lesson=max(candidates,key=lambda n:n["position"])
        node(id,"outline",title,book=bid,section=sid,printed_page=page,pdf_page=page+OFFSETS[bid],
             source_id="source:"+bid,directory_status="verified",body=body,
             treatment="随“"+lesson["title"]+"”阅读或探究，不额外声称为教材规定课时。")
        lesson["data"].setdefault("integrated_readings",[]).append({"id":id,"title":title,"body":body,"printed_page":page,"pdf_page":page+OFFSETS[bid]})
        edge(id,lesson["id"],"covers","此阅读、探究或建模节点融入指定课时，保留独立学习目标。","source:"+bid)
